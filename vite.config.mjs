import fs from "node:fs";
import path from "node:path";
import { defineConfig, minifySync } from "vite-plus";

const root = import.meta.dirname;
const outDir = path.join(root, "assets");

// Baseline Widely Available on 2026-11-20 (baseline-browser-mapping 2.11.39, web-features 3.47): the
// first versions of the core browsers released 30 months earlier, Chrome / Edge 125, Firefox 126,
// Safari 17.5 (macOS and iOS), and everything after. Native nesting and light-dark() are in all of
// them; what some lack (relative colours, anchor positioning, view transitions, @starting-style,
// text-box...) is either rewritten in src/css or guarded, so they get the same content and layout,
// with less decoration. src/tests/browser-support.test.js checks the built files against this list.
// When it moves forward, update the README ("Browser support") and docs/guide-auteur.md too.
export const browsers = ["chrome125", "edge125", "firefox126", "safari17.5", "ios17.5"];

// The same browsers in Lightning CSS form (it lowers and prefixes the CSS for them: -webkit- for
// Safari 17, e.g.); Vite would otherwise lower CSS for its own default targets (Safari 16.4), which
// flattens the native nesting.
const lightningcssTargets = Object.fromEntries(
	browsers.map(b => {
		const [, name, major, minor = 0] = b.match(/^([a-z]+)(\d+)(?:\.(\d+))?$/);
		return [name === "ios" ? "ios_saf" : name, (Number(major) << 16) | (Number(minor) << 8)];
	}),
);

const js = ["app", "home", "post", "page", "archives", "saved", "newsletter", "about", "tags"];
const css = [
	"app",
	"home",
	"listing",
	"post",
	"newsletter",
	"404",
	"page",
	"about",
	"archives",
	"saved",
	"print",
	"tags",
];

// The build writes into assets/, which also holds committed images, fonts and HTML, so it
// cannot empty its output directory: remove the previous JS and CSS output instead.
const cleanBuiltAssets = () => ({
	name: "attibling:clean-built-assets",
	apply: "build",
	buildStart() {
		for (const dir of ["js", "css"]) {
			fs.rmSync(path.join(outDir, dir), { recursive: true, force: true });
		}
	},
});

// assets/html/javascript.html is the LibreJS licence table (linked from the footer): it lists
// every built script, so it is regenerated from the bundle, hashed chunk names included.
const librejsTable = () => ({
	name: "attibling:librejs-table",
	apply: "build",
	writeBundle(options, bundle) {
		const files = Object.values(bundle)
			.filter(file => file.type === "chunk")
			.map(file => file.fileName)
			.sort((a, b) => a.includes("/chunks/") - b.includes("/chunks/") || a.localeCompare(b));
		const rows = files.map(file => {
			const url = `/assets/${file}`;
			const name = file.replace(/^js\//, "");
			return `  <tr>
    <td><a href="${url}">${name}</a></td>
    <td><a href="http://www.jclark.com/xml/copying.txt">Expat</a></td>
    <td><a href="${url}">${name}</a></td>
  </tr>`;
		});
		const html = `<table id="jslicense-labels1">
  <tr>
    <th>Javascript file</th>
    <th>License canonical URL</th>
    <th>Original file</th>
  </tr>
${rows.join("\n\n")}
</table>`;
		fs.writeFileSync(path.join(outDir, "html", "javascript.html"), html);
	},
});

// partials/tags/prepaint.hbs: src/js/tags/layout.js (which has no import) minified into an inline script
// of <head> that arranges the « Tags » grid as soon as the parser has built it, before the style sheets
// have arrived and before the first paint. Handlebars would read "{{" as an expression: it is escaped.
// src/tests/tags.test.js checks that the partial is up to date.
export const tagsPrepaint = () => {
	const source = fs.readFileSync(path.join(root, "src/js/tags/layout.js"), "utf8").replace(/^export /gm, "");
	const { code } = minifySync("prepaint.js", `(() => {\n${source}\nwindow.attiblingTags = prepaint();\n})();`, {
		compress: true,
		mangle: true,
	});
	return `{{!-- Generated by vite.config.mjs from src/js/tags/layout.js (npm run build): do not edit. It arranges the
« Tags » grid before the first paint; it must come in <head>, ahead of the style sheets (the "preload" block of
partials/pages/tags.hbs), so that it does not wait for them. --}}
<script>
// @license magnet:?xt=urn:btih:d3d9a9a6595521f9666a5e94cc830dab83b65699&dn=expat.txt Expat
${code.trim().replaceAll("{{", "\\{{")}
// @license-end
</script>
`;
};

const tagsPrepaintPartial = () => ({
	name: "attibling:tags-prepaint",
	apply: "build",
	buildStart() {
		fs.writeFileSync(path.join(root, "partials/tags/prepaint.hbs"), tagsPrepaint());
	},
});

